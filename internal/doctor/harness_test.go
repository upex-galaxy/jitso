func TestHooksReportsTheOtherHarnessFiles(t *testing.T) {
	dir := fixture(t)
	c, _ := checksFor(t, dir, map[string]int{tracked: 0})
	c.p.LookPath = lookup(map[string]string{"jitso": "/usr/local/bin/jitso"})
	put(t, dir, ".claude/settings.json", string(settingsjson.Fragment(settingsjson.Command)))
	claude := "jitso hook guard is registered on PreToolUse (Bash, orca MCP) and SessionEnd in .claude/settings.json"

	// No harness file: the Claude Code line as it was.
	got := c.hooks()
	if got.Status != OK || got.Detail != claude {
		t.Fatalf("got %s", got)
	}

	// A registered Codex file and generated files are ok parts.
	put(t, dir, ".codex/hooks.json", string(settingsjson.Fragment(settingsjson.Command)))
	put(t, dir, ".opencode/plugins/jitso-guard.js", string(guardfiles.OpenCode("jitso", "v1.0.0")))
	bin := filepath.Join(t.TempDir(), "jitso")
	if err := os.WriteFile(bin, []byte("#!/bin/sh\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	put(t, dir, ".pi/extensions/jitso-guard.js", string(guardfiles.Pi(bin, "v1.0.0")))
	got = c.hooks()
	wantDetail := claude +
		"; codex: jitso hook guard is registered on PreToolUse (Bash, orca MCP) and SessionEnd in .codex/hooks.json" +
		"; opencode: guard plugin .opencode/plugins/jitso-guard.js generated by jitso v1.0.0" +
		"; pi: guard extension .pi/extensions/jitso-guard.js generated by jitso v1.0.0"
	if got.Status != OK || got.Detail != wantDetail {
		t.Fatalf("got %s\nwant detail %s", got, wantDetail)
	}

	// A partial Codex file and a file jitso did not write warn.
	put(t, dir, ".codex/hooks.json", `{"hooks": {"PreToolUse": [{"matcher": "Bash", "hooks": [{"type": "command", "command": "jitso hook guard"}]}]}}`)
	put(t, dir, ".opencode/plugins/jitso-guard.js", "// mine\n")
	got = c.hooks()
	want(t, got, Warn, "hooks", "; codex: registered on PreToolUse Bash only (missing PreToolUse orca MCP, SessionEnd): run jitso setup hook --harness codex;")
	want(t, got, Warn, "hooks", "; opencode: .opencode/plugins/jitso-guard.js was not written by jitso setup hook (no generated marker);")

	// A command that cannot start warns, it never fails the line.
	c.p.LookPath = lookup(map[string]string{})
	put(t, dir, ".claude/settings.json", `{"hooks": {"Stop": []}}`)
	put(t, dir, ".codex/hooks.json", "{")
	put(t, dir, ".opencode/plugins/jitso-guard.js", string(guardfiles.OpenCode("jitso", "v1.0.0")))
	got = c.hooks()
	want(t, got, Warn, "hooks", "; codex: .codex/hooks.json is not valid JSON")
	want(t, got, Warn, "hooks", "; opencode: guard plugin .opencode/plugins/jitso-guard.js generated by jitso v1.0.0: jitso is not on PATH")
	os.Remove(bin)
	want(t, c.hooks(), Warn, "hooks", "; pi: guard extension .pi/extensions/jitso-guard.js generated by jitso v1.0.0: "+bin+" does not exist")
}

func TestHooksUserReportsTheOtherHarnessFiles(t *testing.T) {
	home := t.TempDir()
	env := map[string]string{}
	p := Ports{GOOS: "linux", Home: home, LookPath: lookup(map[string]string{"jitso": "/usr/local/bin/jitso"}), Getenv: func(k string) string { return env[k] }}.withDefaults()

	put(t, home, ".codex/hooks.json", string(settingsjson.Fragment(settingsjson.Command)))
	put(t, home, ".config/opencode/plugins/jitso-guard.js", string(guardfiles.OpenCode("jitso", "dev")))
	got, guarded := checkHooksUser(p)
	if guarded {
		t.Error("another harness's guard counts as the Claude Code guard")
	}
	want(t, got, OK, "hooks-user", "(optional: run jitso setup hook --scope user to guard your own session); codex: jitso hook guard is registered on PreToolUse (Bash, orca MCP) and SessionEnd in ~/.codex/hooks.json; opencode: guard plugin ~/.config/opencode/plugins/jitso-guard.js generated by jitso dev")

	// CODEX_HOME moves the Codex file.
	env["CODEX_HOME"] = home + "/cx"
	put(t, home, "cx/hooks.json", `{"hooks": {"SessionEnd": [{"hooks": [{"type": "command", "command": "jitso hook guard"}]}]}}`)
	got, _ = checkHooksUser(p)
	want(t, got, Warn, "hooks-user", "; codex: registered on SessionEnd only (missing PreToolUse Bash, PreToolUse orca MCP): run jitso setup hook --harness codex --scope user;")
}

func TestGuardProgram(t *testing.T) {
	for _, tc := range []struct {
		in, want string
		ok       bool
	}{
		{string(guardfiles.Pi(`/a b/"q"/jitso`, "dev")), `/a b/"q"/jitso`, true},
		{"const command = \"jitso\";\r\n", "jitso", true},
		{"const command = jitso;\n", "", false},
		{"", "", false},
	} {
		got, ok := guardProgram([]byte(tc.in))
		if got != tc.want || ok != tc.ok {
			t.Errorf("guardProgram(%q) = %q, %v", strings.SplitN(tc.in, "\n", 2)[0], got, ok)
		}
	}
}
