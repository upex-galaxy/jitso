// Package guardfiles generates the JavaScript files that run `jitso hook
// guard` inside the harnesses that take no command hook: the OpenCode 2 plugin
// and the Pi extension. Each file starts with a marker line, so `jitso setup
// hook` can tell a file it generated (upgraded freely) from one a person wrote
// (replaced only with --force).
//
// Both files run the guard synchronously with node:child_process spawnSync
// (Bun has it too), send it a Claude Code shaped hook input on stdin, and read
// its answer the way Claude Code does: one JSON object whose
// hookSpecificOutput.permissionDecision is "deny" blocks the call with
// permissionDecisionReason. They fail open, like a command hook that cannot
// start: when the command cannot run, prints nothing or prints something that
// is not that object, the call goes through.
package guardfiles

import (
	"regexp"
	"strings"

	"github.com/upex-galaxy/jitso/internal/jsonx"
)

// markerLine matches the first line of a generated file and captures the
// jitso version it names.
var markerLine = regexp.MustCompile(`^// generated by jitso (\S+): jitso setup hook; do not edit$`)

// marker is the first line of a generated file.
func marker(version string) string {
	return "// generated by jitso " + version + ": jitso setup hook; do not edit\n"
}

// MarkerVersion is the jitso version named by the marker line that starts
// content; ok is false when content does not start with a marker line, that
// is when jitso did not generate it.
func MarkerVersion(content []byte) (version string, ok bool) {
	first, _, _ := strings.Cut(string(content), "\n")
	m := markerLine.FindStringSubmatch(strings.TrimSuffix(first, "\r"))
	if m == nil {
		return "", false
	}
	return m[1], true
}

// jsString is s as a JavaScript string literal (a JSON string is one).
func jsString(s string) string {
	b, err := jsonx.Marshal(s)
	if err != nil { // a Go string always encodes
		panic("guardfiles: " + err.Error())
	}
	return strings.TrimSuffix(string(b), "\n")
}

// runGuard is the part both files share: the command, and the function that
// runs it with ["hook", "guard"] and returns the deny reason, or undefined to
// let the call through.
const runGuard = `import { spawnSync } from "node:child_process";

const command = %COMMAND%;

// guard runs the JITSO guard with a Claude Code shaped hook input and returns
// the reason when it denies the call; undefined lets the call through, also
// when the guard cannot start, answers nothing or runs past 30 seconds (fail
// open, like a command hook that times out).
function guard(input, cwd) {
  let res;
  try {
    res = spawnSync(command, ["hook", "guard"], { input: JSON.stringify(input), encoding: "utf8", cwd, timeout: 30000 });
  } catch {
    return undefined;
  }
  if (!res || res.error || typeof res.stdout !== "string" || res.stdout.trim() === "") return undefined;
  let answer;
  try {
    answer = JSON.parse(res.stdout);
  } catch {
    return undefined;
  }
  const out = answer && answer.hookSpecificOutput;
  if (out && out.permissionDecision === "deny") {
    return typeof out.permissionDecisionReason === "string" && out.permissionDecisionReason !== ""
      ? out.permissionDecisionReason
      : "denied by the JITSO guard";
  }
  return undefined;
}
`

const openCodeBody = `
// setup registers the guard before every tool call. OpenCode 2 runs only this
// form (an object with id and setup); a thrown error blocks the call. The
// guard runs in the session's project folder: opencode run hands the work
// to a background service whose own folder is not the project.
// toolName is the Claude Code name of an OpenCode tool: the shell is Bash, and
// an MCP tool of a server whose name holds "orca", which OpenCode names
// <server>_<tool> (also when Code Mode's execute calls it), is
// mcp__<server>__<tool>, the form the guard reads.
function toolName(t) {
  if (t === "shell" || t === "bash") return "Bash";
  if (typeof t === "string" && !t.startsWith("mcp__")) {
    const i = t.indexOf("_");
    if (i > 0 && /orca/i.test(t.slice(0, i))) return "mcp__" + t.slice(0, i) + "__" + t.slice(i + 1);
  }
  return t;
}

async function setup(ctx) {
  const dir = ctx?.location?.directory ?? process.cwd();
  const reg = await ctx.tool.hook("execute.before", async (p) => {
    const tool = toolName(p.tool);
    const reason = guard({ hook_event_name: "PreToolUse", tool_name: tool, tool_input: p.input, cwd: dir, session_id: p.sessionID }, dir);
    if (reason !== undefined) throw new Error(reason);
  });
  return async () => {
    await reg?.dispose?.();
  };
}

export default { id: "jitso-guard", setup };
`

const piBody = `
// The guard judges every tool call (a deny blocks it) and hears the end of the
// session (its answer is ignored).
export default function (pi) {
  pi.on("tool_call", async (event, ctx) => {
    const cwd = ctx?.cwd ?? process.cwd();
    const tool = event.toolName === "bash" ? "Bash" : event.toolName;
    const reason = guard({ hook_event_name: "PreToolUse", tool_name: tool, tool_input: event.input, cwd, session_id: ctx?.sessionManager?.getSessionId?.() }, cwd);
    if (reason !== undefined) return { block: true, reason };
    return undefined;
  });
  pi.on("session_shutdown", async (event, ctx) => {
    const cwd = ctx?.cwd ?? process.cwd();
    guard({ hook_event_name: "SessionEnd", session_id: ctx?.sessionManager?.getSessionId?.(), cwd, reason: event?.reason }, cwd);
  });
}
`

// generate is the marker, the shared part with command as argv[0], and body.
func generate(command, version, body string) []byte {
	return []byte(marker(version) + strings.Replace(runGuard, "%COMMAND%", jsString(command), 1) + body)
}

// OpenCode is the OpenCode 2 plugin (`.opencode/plugins/jitso-guard.js`):
// `export default { id: "jitso-guard", setup }`, whose setup hooks
// `execute.before`. A shell or bash tool is sent as tool_name "Bash" and an
// orca MCP tool (<server>_<tool>) as mcp__<server>__<tool>; the
// guard runs in ctx.location.directory, the session's project folder; a deny
// throws an Error with the reason. command is the program the plugin starts
// (argv[0], "jitso" or an absolute path) with the arguments hook guard;
// version is the jitso version for the marker line.
func OpenCode(command string, version string) []byte {
	return generate(command, version, openCodeBody)
}

// Pi is the Pi extension (`.pi/extensions/jitso-guard.js`): `export default
// function (pi)` with a tool_call handler (bash is sent as "Bash", other tool
// names as they are; a deny returns { block: true, reason }) and a
// session_shutdown handler that sends a SessionEnd input and ignores the
// answer. command and version are as for OpenCode.
func Pi(command string, version string) []byte {
	return generate(command, version, piBody)
}
