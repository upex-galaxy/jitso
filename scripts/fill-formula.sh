#!/bin/sh
# Fills the Homebrew formula template with a release's version and checksums.
#
# Usage: scripts/fill-formula.sh <version without v> <checksums.txt> <out.rb>
#
# Reads the four archive checksums by asset name from the checksums.txt of the
# release, writes the formula for the tap repository, and fails when a
# placeholder is left over. It reads and writes local files only.
set -eu

usage="usage: scripts/fill-formula.sh <version without v> <checksums.txt> <out.rb>"
[ "$#" -eq 3 ] || { echo "$usage" >&2; exit 2; }
version=$1
sums=$2
out=$3
case "$version" in
  v*) echo "fill-formula: give the version without the leading v: $version" >&2; exit 2 ;;
  [0-9]*.[0-9]*.[0-9]*) ;;
  *) echo "fill-formula: the version must look like 1.2.3: $version" >&2; exit 2 ;;
esac
case "$version" in
  *[!0-9A-Za-z.-]*) echo "fill-formula: bad characters in the version: $version" >&2; exit 2 ;;
esac
[ -f "$sums" ] || { echo "fill-formula: no such file: $sums" >&2; exit 1; }

root=$(cd "$(dirname "$0")/.." && pwd)
template="$root/packaging/homebrew/jitso.rb"
[ -f "$template" ] || { echo "fill-formula: no template at $template" >&2; exit 1; }

sum() { # sum <asset>: the SHA-256 the checksums file gives for the asset
  hex=$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1; exit }' "$sums")
  case "$hex" in
    "") echo "fill-formula: $sums has no line for $1" >&2; exit 1 ;;
    *[!0-9a-f]*) echo "fill-formula: the checksum of $1 is not lower-case hex" >&2; exit 1 ;;
  esac
  [ "${#hex}" -eq 64 ] || { echo "fill-formula: the checksum of $1 is not 64 hex digits" >&2; exit 1; }
  printf '%s' "$hex"
}

darwin_arm64=$(sum jitso-darwin-arm64.tar.gz)
darwin_amd64=$(sum jitso-darwin-amd64.tar.gz)
linux_arm64=$(sum jitso-linux-arm64.tar.gz)
linux_amd64=$(sum jitso-linux-amd64.tar.gz)

tmp="$out.tmp.$$"
trap 'rm -f "$tmp"' EXIT
{
  printf '# Generated by scripts/fill-formula.sh from packaging/homebrew/jitso.rb for v%s.\n' "$version"
  printf '# Do not edit by hand: fill the template again for the next release.\n'
  sed -n '/^class /,$p' "$template" |
    sed -e "s/@VERSION@/$version/g" \
      -e "s/@SHA256_DARWIN_ARM64@/$darwin_arm64/g" \
      -e "s/@SHA256_DARWIN_AMD64@/$darwin_amd64/g" \
      -e "s/@SHA256_LINUX_ARM64@/$linux_arm64/g" \
      -e "s/@SHA256_LINUX_AMD64@/$linux_amd64/g"
} > "$tmp"
if grep -q '@[A-Z0-9_]*@' "$tmp"; then
  echo "fill-formula: a placeholder is left in the output:" >&2
  grep -n '@[A-Z0-9_]*@' "$tmp" >&2
  exit 1
fi
mv -f "$tmp" "$out"
echo "fill-formula: wrote $out for v$version"
