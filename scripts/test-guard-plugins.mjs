#!/usr/bin/env node
// Tests the guard files `jitso setup hook` generates for OpenCode
// (.opencode/plugins/jitso-guard.js) and Pi (.pi/extensions/jitso-guard.js),
// without OpenCode or Pi: it generates both through the built binary, imports
// them with a fake OpenCode ctx and a fake Pi object, and checks that a deny
// blocks the call, an allow lets it through, and a guard that cannot answer
// fails open. The files run the bare word jitso, so each check puts the jitso
// it wants first on PATH: a fake that denies when its stdin contains
// FORBIDDEN, the real binary (which denies a direct harness in a project with
// jitso/jitso.yaml), or none at all.
//
// Usage, from the repo root (node, no dependencies; POSIX, the fake is a
// /bin/sh script):
//   node scripts/test-guard-plugins.mjs              builds the binary with go
//   node scripts/test-guard-plugins.mjs <jitso>      uses a binary already built
//
// Every check prints "ok <name>" or "FAIL <name>"; the exit code is 1 when any
// check fails. It runs in throwaway folders under the OS temp folder and never
// touches the real HOME.
import { execFileSync, spawnSync } from "node:child_process";
import { chmodSync, copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { delimiter, dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const scratch = mkdtempSync(join(tmpdir(), "jitso-guard-plugins-"));
let failed = 0;

function check(name, ok, detail) {
  if (ok) {
    console.log(`ok ${name}`);
  } else {
    failed++;
    console.log(`FAIL ${name}${detail === undefined ? "" : `: ${detail}`}`);
  }
}

async function outcome(fn) {
  try {
    return { value: await fn() };
  } catch (err) {
    return { error: err };
  }
}

function binary() {
  if (process.argv.length > 3) {
    console.error("usage: node scripts/test-guard-plugins.mjs [<jitso binary>]");
    process.exit(2);
  }
  if (process.argv[2]) return resolve(process.argv[2]);
  const out = join(scratch, "build", "jitso");
  execFileSync("go", ["build", "-o", out, "./cmd/jitso"], { cwd: repoRoot, stdio: "inherit" });
  return out;
}

// A folder holding one program named jitso: a link to target, or the fake.
function jitsoDir(name, target) {
  const dir = join(scratch, name);
  mkdirSync(dir, { recursive: true });
  if (target) {
    symlinkSync(target, join(dir, "jitso"));
  } else {
    writeFileSync(
      join(dir, "jitso"),
      `#!/bin/sh
input=$(cat)
[ -n "$FAKE_LOG" ] && printf '%s\\n' "$input" >> "$FAKE_LOG"
case "$FAKE_MODE" in
  garbage) echo 'not json'; exit 0 ;;
  crash) exit 1 ;;
esac
case "$input" in
  *FORBIDDEN*) printf '%s\\n' '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"fake guard: FORBIDDEN"}}' ;;
esac
exit 0
`,
    );
    chmodSync(join(dir, "jitso"), 0o755);
  }
  return dir;
}

const systemPath = ["/usr/bin", "/bin"].join(delimiter);
function usePath(dir) {
  process.env.PATH = dir ? dir + delimiter + systemPath : systemPath;
}

function logLines(file) {
  try {
    return readFileSync(file, "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));
  } catch {
    return [];
  }
}

async function main() {
  const jitso = binary();

  // A project with jitso/jitso.yaml, and the two files generated in it.
  const repo = join(scratch, "repo");
  const home = join(scratch, "home");
  mkdirSync(join(repo, "jitso"), { recursive: true });
  mkdirSync(home, { recursive: true });
  execFileSync("git", ["init", "-q"], { cwd: repo });
  writeFileSync(join(repo, "jitso", "jitso.yaml"), "builds: {}\n");
  const gen = spawnSync(jitso, ["setup", "hook", "--harness", "opencode,pi", "--yes"], {
    cwd: repo,
    encoding: "utf8",
    env: { HOME: home, PATH: systemPath },
  });
  check("setup hook --harness opencode,pi --yes exits 0", gen.status === 0, `exit ${gen.status}: ${gen.stderr}`);
  const ocFile = join(repo, ".opencode", "plugins", "jitso-guard.js");
  const piFile = join(repo, ".pi", "extensions", "jitso-guard.js");
  for (const [name, file] of [["opencode", ocFile], ["pi", piFile]]) {
    const text = readFileSync(file, "utf8");
    check(`${name} file starts with the generated marker`, /^\/\/ generated by jitso \S+: jitso setup hook; do not edit\n/.test(text));
    check(`${name} file runs the bare word jitso`, text.includes('\nconst command = "jitso";\n'));
  }

  // Node reads a .js file outside a module package as CommonJS: import copies
  // with the .mjs extension, byte for byte.
  copyFileSync(ocFile, join(scratch, "opencode.mjs"));
  copyFileSync(piFile, join(scratch, "pi.mjs"));
  const oc = (await import(pathToFileURL(join(scratch, "opencode.mjs")).href)).default;
  const piExt = (await import(pathToFileURL(join(scratch, "pi.mjs")).href)).default;

  // OpenCode: a fake ctx whose tool.hook keeps the handler.
  check("opencode plugin is { id: jitso-guard, setup }", oc && oc.id === "jitso-guard" && typeof oc.setup === "function");
  const hooks = {};
  let disposed = false;
  // OpenCode's background service runs in another folder than the project:
  // the plugin must take the project from ctx.location.directory.
  const ctx = {
    location: { directory: repo },
    tool: {
      hook: async (name, fn) => {
        hooks[name] = fn;
        return { dispose: async () => { disposed = true; } };
      },
    },
  };
  const cleanup = await oc.setup(ctx);
  const before = hooks["execute.before"];
  check("opencode plugin registers execute.before", typeof before === "function");

  // Pi: a fake pi whose on keeps the handlers.
  const handlers = {};
  piExt({ on: (event, fn) => { handlers[event] = fn; } });
  check("pi extension handles tool_call and session_shutdown", typeof handlers.tool_call === "function" && typeof handlers.session_shutdown === "function");
  const piCtx = { cwd: repo, sessionManager: { getSessionId: () => "pi-session-1" } };

  const fake = jitsoDir("fake");
  const log = join(scratch, "fake.log");
  process.env.FAKE_LOG = log;
  usePath(fake);
  process.chdir(home);

  // Deny.
  let r = await outcome(() => before({ tool: "shell", sessionID: "oc-1", input: { command: "echo FORBIDDEN" } }));
  check("opencode: a deny throws the reason", r.error instanceof Error && r.error.message === "fake guard: FORBIDDEN", r.error ?? "no error");
  const sent = logLines(log).at(-1) ?? {};
  check(
    "opencode: the guard gets a Claude-shaped PreToolUse input",
    sent.hook_event_name === "PreToolUse" && sent.tool_name === "Bash" && sent.tool_input?.command === "echo FORBIDDEN" && sent.session_id === "oc-1" && sent.cwd === repo,
    JSON.stringify(sent),
  );
  r = await outcome(() => handlers.tool_call({ toolName: "bash", input: { command: "echo FORBIDDEN" } }, piCtx));
  check("pi: a deny returns { block: true, reason }", r.value?.block === true && r.value?.reason === "fake guard: FORBIDDEN", JSON.stringify(r));
  const piSent = logLines(log).at(-1) ?? {};
  check(
    "pi: the guard gets a Claude-shaped PreToolUse input",
    piSent.tool_name === "Bash" && piSent.session_id === "pi-session-1" && piSent.cwd === repo,
    JSON.stringify(piSent),
  );

  // Allow.
  r = await outcome(() => before({ tool: "shell", sessionID: "oc-1", input: { command: "ls" } }));
  check("opencode: an allow lets the call through", !r.error, r.error);
  r = await outcome(() => before({ tool: "read", sessionID: "oc-1", input: { filePath: "FORBIDDEN-not-a-command" } }));
  check("opencode: another tool keeps its name", logLines(log).at(-1)?.tool_name === "read");
  r = await outcome(() => handlers.tool_call({ toolName: "bash", input: { command: "ls" } }, piCtx));
  check("pi: an allow lets the call through", !r.error && r.value === undefined, JSON.stringify(r));
  await handlers.tool_call({ toolName: "read", input: { path: "x" } }, piCtx);
  check("pi: another tool keeps its name", logLines(log).at(-1)?.tool_name === "read");

  // Session end (Pi): the guard hears it, the answer is ignored.
  r = await outcome(() => handlers.session_shutdown({ type: "session_shutdown", reason: "quit" }, piCtx));
  const end = logLines(log).at(-1) ?? {};
  check(
    "pi: session_shutdown sends SessionEnd",
    !r.error && end.hook_event_name === "SessionEnd" && end.session_id === "pi-session-1" && end.reason === "quit" && end.cwd === repo,
    JSON.stringify(end),
  );

  // Fail open: a guard that prints something else, exits non-zero, or is not on PATH.
  for (const mode of ["garbage", "crash"]) {
    process.env.FAKE_MODE = mode;
    r = await outcome(() => before({ tool: "shell", sessionID: "oc-1", input: { command: "echo FORBIDDEN" } }));
    check(`opencode: fails open when the guard answers ${mode}`, !r.error, r.error);
    r = await outcome(() => handlers.tool_call({ toolName: "bash", input: { command: "echo FORBIDDEN" } }, piCtx));
    check(`pi: fails open when the guard answers ${mode}`, !r.error && r.value === undefined, JSON.stringify(r));
  }
  delete process.env.FAKE_MODE;
  usePath(null);
  r = await outcome(() => before({ tool: "shell", sessionID: "oc-1", input: { command: "echo FORBIDDEN" } }));
  check("opencode: fails open when jitso is not on PATH", !r.error, r.error);
  r = await outcome(() => handlers.tool_call({ toolName: "bash", input: { command: "echo FORBIDDEN" } }, piCtx));
  check("pi: fails open when jitso is not on PATH", !r.error && r.value === undefined, JSON.stringify(r));

  // The real guard: a harness started directly in a JITSO project is denied.
  usePath(jitsoDir("real", jitso));
  r = await outcome(() => before({ tool: "shell", sessionID: "oc-1", input: { command: "claude -p hi" } }));
  check("opencode: the real guard denies claude -p hi", r.error instanceof Error && r.error.message.endsWith("(denied: claude)"), r.error ?? "no error");
  r = await outcome(() => handlers.tool_call({ toolName: "bash", input: { command: "pi -p hi" } }, piCtx));
  check("pi: the real guard denies pi -p hi", r.value?.block === true && r.value.reason.endsWith("(denied: pi)"), JSON.stringify(r));
  r = await outcome(() => handlers.tool_call({ toolName: "bash", input: { command: "git status" } }, piCtx));
  check("pi: the real guard allows git status", !r.error && r.value === undefined, JSON.stringify(r));
  r = await outcome(() => before({ tool: "shell", sessionID: "oc-1", input: { command: "claude --version" } }));
  check("opencode: the real guard allows claude --version", !r.error, r.error);
  // OpenCode names an MCP tool <server>_<tool>, also inside Code Mode's
  // execute (measured on 2.3.2): an orca server's start_worker is denied.
  r = await outcome(() => before({ tool: "orca-bridge_start_worker", sessionID: "oc-1", input: { runId: "r", spec: "s", placement: "p" } }));
  check("opencode: the real guard denies orca-bridge_start_worker", r.error instanceof Error && r.error.message.includes("(denied: "), r.error ?? "no error");
  r = await outcome(() => before({ tool: "probe-srv_mem_search", sessionID: "oc-1", input: { query: "x" } }));
  check("opencode: another server's MCP tool passes", !r.error, r.error);
  r = await outcome(() => handlers.tool_call({ toolName: "mcp__orca-bridge__start_worker", input: { runId: "r", spec: "s", placement: "p" } }, piCtx));
  check("pi: the real guard denies mcp__orca-bridge__start_worker", r.value?.block === true, JSON.stringify(r));

  await cleanup();
  check("opencode: the cleanup disposes the hook", disposed);
}

try {
  await main();
} catch (err) {
  failed++;
  console.log(`FAIL unexpected error: ${err?.stack ?? err}`);
} finally {
  process.chdir(repoRoot);
  rmSync(scratch, { recursive: true, force: true });
}
process.exit(failed > 0 ? 1 : 0);
